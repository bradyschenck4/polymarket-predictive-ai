# 2. High-frequency feature engineering
# Encode trade direction (BUY = 1, SELL = -1)
df['side_sign'] = df['side'].map({'BUY': 1, 'SELL': -1}).fillna(0)

# Signed order flow volume
df['signed_volume'] = df['side_sign'] * df['size']

# Price differences & returns across recent trades
df['price_lag1_diff'] = df.groupby('asset_id')['price'].diff(1)
df['price_lag3_diff'] = df.groupby('asset_id')['price'].diff(3)
df['size_lag1'] = df.groupby('asset_id')['size'].shift(1)

# Rolling price momentum and volatility over past 5 trades
df['rolling_mean_5'] = df.groupby('asset_id')['price'].rolling(5).mean().reset_index(0, drop=True)
df['rolling_std_5'] = df.groupby('asset_id')['price'].rolling(5).std().reset_index(0, drop=True).fillna(0)

# Order flow imbalance (OFI) over past 5 trades
df['rolling_ofi_5'] = df.groupby('asset_id')['signed_volume'].rolling(5).sum().reset_index(0, drop=True)

# Time delta between trades (in milliseconds)
df['delta_time_ms'] = df.groupby('asset_id')['ts_ms'].diff()

