def predict_polymarket_edge(model, market_question, current_prob, volatility, momentum, dispersion):
    """
    Computes model probability forecast and compares against Polymarket implied price.
    """
    input_data = pd.DataFrame([{
        'probability': current_prob,
        'volatility': volatility,
        'momentum': momentum,
        'price_dispersion': dispersion
    }])

    model_prob = model.predict_proba(input_data)[0, 1]
    edge = model_prob - current_prob

    if edge > 0.05:
        recommendation = "UNDERVALUED (Buy YES contract)"
    elif edge < -0.05:
        recommendation = "OVERVALUED (Sell YES / Buy NO contract)"
    else:
        recommendation = "FAIRLY PRICED (Hold / Pass)"

    return {
        "Market Question": market_question,
        "Polymarket Price": current_prob,
        "Model Forecast": round(float(model_prob), 4),
        "Estimated Edge": round(float(edge), 4),
        "Signal": recommendation
    }

# Example utilization on a test market
